/**
 * 공성계 (siege_riichi, prism) — **텐파이가 아니어도 리치를 선언할 수 있다.**
 * 가짜 리치로 테이블을 접게 만드는 순수 심리전. 걸고 나면 손이 잠기고 쯔모기리가
 * 강제되는 것은 진짜 리치와 같다 — 다만 화료는 애초에 불가능하다.
 *
 * 부수는 상식: "리치는 텐파이 선언"이라는 대전제. 노텐 리치로 상대를 속인다.
 *
 * 도파민 순간: 누가 봐도 위험한 판에 홀더가 리치를 때린다 — 셋이 전부 손을 접고
 * 안전패만 버리는데, 정작 홀더 손은 텐파이가 아니다. 유국이 나야 진실이 드러난다.
 *
 * 대응: 리치봉 1000점과 노텐 벌부가 그대로 걸리는 자해다 — 홀더가 리치 후에도
 * 값싼 손처럼 굴면 블러프를 의심하라. 쯔모기리라 홀더의 버림은 정보가 되지 않는다.
 *
 * 구현: 코어 규칙 `riichi.requiresTenpai`(보유자 전용, false) 하나. 리치 액션 validate가
 * 텐파이 검사를 이 규칙으로 게이트한다. 손 잠금·쯔모기리·리치봉·노텐 판정은 표준 그대로 —
 * 텐파이가 아니므로 winningKinds가 0이라 유국에 자동으로 노텐 처리된다.
 */

import { defineAugment } from "@majak/core";
import type { AugmentDef } from "@majak/core";

export const siegeRiichi: AugmentDef = defineAugment({
  id: "siege_riichi",
  tier: "prism",
  category: "riichi",
  complexity: 2,
  name: "공성계",
  description:
    "텐파이가 아니어도 가짜 리치를 걸 수 있다(그 상태로는 화료 불가)",
  detail:
    "텐파이가 아니어도 리치를 걸 수 있다 — 그 상태로는 화료할 수 없다.\n\n손이 잠기고 쯔모기리가 강제되며, 리치봉 1,000점과 유국 노텐 벌점은 그대로 문다.",
  /*
   * 승승장구(always_tenpai)와는 **함께 들 수 없다** (2026-08-23 QA synergy3 disrupt 확정 5).
   *
   * 이 증강의 대가는 detail이 적은 두 가지, 리치봉 1,000점과 **노텐 벌부**뿐이다.
   * 그런데 승승장구는 유국에서 손패가 어떻든 텐파이로 잡아 주므로 노텐 리치가
   * ① 벌부를 안 내고 ② 노텐인 상대에게서 2,000씩 더 걷는 쪽으로 뒤집힌다 —
   * 실측으로 노텐 리치가 **대조군 대비 +4,500**의 순이익이 됐고, 그 위에 "셋이 전부
   * 접는" 심리 효과가 공짜로 얹혔다. 「자해가 억제 장치」라는 설계가 통째로 사라진다.
   *
   * `antiIds`가 아니라 `conflicts`인 이유: antiIds는 드래프트 **확률만** 기울여서
   * 두 장이 여전히 한 사람에게 갈 수 있다(synergy.ts 머리말 — "진짜로 같이 들면
   * 안 되는 것은 AugmentDef.conflicts로 잠근다"). 여기서 깨지는 것은 시너지의
   * 좋고 나쁨이 아니라 카드가 적어 둔 **대가 자체**라 확률로는 닫히지 않는다.
   * 배타는 같은 사람의 보유 안에서만 성립하는데, 이 결함도 정확히 한 사람이 둘을
   * 들었을 때만 난다(남의 승승장구는 내 노텐 벌부를 면제해 주지 않는다).
   * 승승장구는 이미 `die_hard`와 같은 방식으로 잠겨 있다.
   */
  conflicts: ["always_tenpai"],
  install(ctx) {
    ctx.setHolderRule("riichi.requiresTenpai", false);
  },
});
