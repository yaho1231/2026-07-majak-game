/**
 * 양극 (polar_ends, prism) — **1과 9만으로 몸통(커쯔)을 이룬다.**
 * 같은 무늬의 1·9를 동일 패로 보고, 199·191·911 세 장을 하나의 커쯔로 취급한다.
 * 순수 커쯔(111·999)는 기존처럼이고, 새로 생기는 것은 1과 9가 섞인 몸통뿐이다.
 *
 * 부수는 상식: 숫자는 이어져야(슌쯔) 혹은 같아야(커쯔) 몸통이 된다 — 숫자선의 양 끝이
 * 하나로 접힌다. 1과 9만 잔뜩 쥔, 누가 봐도 못 만드는 손이 그대로 4멘쯔로 완성된다.
 *
 * 도파민 순간: 1·9만 그득한 손을 펼치며 화료 — 찬타·준찬타·혼노두가 자동으로 따라붙어
 * 값도 크다. "그게 몸통이 된다고?" 하는 순간이 매 화료에 나온다.
 *
 * 대응: 홀더의 요구패(1·9) 수집이 노골적이라 읽기는 쉽다 — 1·9를 흘리지 않으면 되지만,
 * 안전패의 절반(노두패)이 통째로 위험패가 되는 압박이 진짜 효과다.
 *
 * 구현: 코어 규칙 `scoring.polarEnds`(보유자 전용). decompose.extractSets가 같은 무늬의
 * 1·9 혼합 커쯔 후보를 만들고(순수 커쯔는 기존 경로), scoringOptionsOf가 화료·텐파이·대기
 * 판정에 같은 옵션을 흘린다. **머리(작두)는 표준대로 같은 패 2장** — 1·9 혼합 머리는 없다.
 *
 * ⚠ 혼합 몸통은 커쯔로 취급되므로 삼색동각(무늬 요구)에는 잡히지 않는다(랭크가 섞임).
 *    클라 waitDecompOptions도 이 옵션을 미러링해야 대기 표시가 맞다.
 *
 * ## 역만까지 가는 것은 의도된 설계다 (2026-08-03 사용자 확정)
 *
 * 감사에서 "청노두 + 스안커 = 더블 역만 상시화"가 결함으로 제기됐다. 그러나 이 증강의
 * 전제는 **1과 9가 한 패로 통한다**는 것이고, 혼합 몸통은 진짜 커쯔로 취급된다 —
 * 그래서 또이또이·산안커가 붙고, 손 전체가 그 몸통이면 스안커·청노두까지 자연히
 * 이어진다. 실전 도달률이 정통 청노두보다 높은 것은 이 증강을 뽑은 대가다.
 * **버그가 아니므로 막지 않는다.**
 *
 * ⚠ 펑 한정 규칙이지만 **가깡으로 1·9 혼합 깡(1만1만9만9만)이 나온다.**
 *    `WinContext.meldToSet`의 `isPolarBody`가 이걸 커쯔로 지켜 준다 — 랭크가 섞였다고
 *    슌쯔성 몸통(장사진·바람의 계보 경로)으로 보내면 또이또이·산안커가 통째로 날아간다.
 */

