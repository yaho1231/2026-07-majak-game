/**
 * 증강 한 줄 요약 — 게임 화면에 **기본으로** 뜨는 설명.
 *
 * 설명은 세 겹으로 적혀 있지만 **플레이어가 읽는 것은 두 겹뿐**이다.
 *
 * | 층 | 내용 | 사는 곳 | 화면 |
 * |----|------|---------|------|
 * | 요약 | "이게 뭘 하는 증강인가" 딱 한 문장 | **이 파일** | 늘 보인다 |
 * | 상세 | 핵심 내용과 핵심 조건 | `AugmentDef.detail` | 펼치면 보인다 |
 * | 설명 | 조건·예외까지 포함한 정식 문장 | `AugmentDef.description` | **본문은 안 뜬다** |
 *
 * ⚠ `description` **본문은 화면 어디에도 나오지 않는다.** 뜨는 것은 맨 앞 괄호 머리말뿐이고
 * (배지와 다를 때 `AugDesc`가 조건 줄로 세운다), 도감 상세는 그 괄호마저 그리지 않는다.
 * 그러니 **핵심 조건을 description에만 적으면 그 조건은 게임에 없는 것과 같다** —
 * 2026-08-26 감사에서 15종이 그 상태였다(날치기의 멘젠 유지, 무덤 도굴의 쯔모 취급 지불,
 * 뒤섞인 아홉 개의 연꽃의 성립 배열 …). 조건은 요약이나 상세에 적는다.
 *
 * **펼치면 어디서나 «상세»가 온다** (2026-08-23 사용자 지시로 통일). 요약은 늘 보이고,
 * 드래프트 카드·인게임 이름표 툴팁·도감 상세·샌드박스 상세 넷 다 그 아래에 도감의
 * 상세를 편다. 예전에는 앞의 둘만 `description`(정식 문장)을 펴서, 판 중에 Shift로
 * 읽은 글을 나중에 도감에서 찾으면 다른 글이 나왔다.
 *
 * 상세가 아직 없는 증강은 설명이 그 자리를 대신한다 — 빈 패널을 두지 않는다.
 *
 * 드래프트 카드와 이름표 툴팁은 좁다 — 요약이 길어지면 그 자리에서 다섯 줄을 넘긴다.
 * 그래서 요약은 **60자 안쪽**을 지킨다(`test/augmentBrief.test.ts`가 지킨다).
 *
 * ## 새 증강을 추가할 때
 * 여기 항목을 같은 커밋에서 넣는다. 빠지면 `briefOf`가 description 앞부분으로
 * 대체 표시하므로 화면이 깨지진 않지만, 길고 어려운 원문이 그대로 노출된다.
 *
 * `use`는 사용 빈도 배지다. 본문에서 `(상시)`·`(매 국 1회)` 같은 머리말을 떼어내
 * 배지로 옮긴 것이라, 요약 본문은 순수하게 효과만 말한다.
 *
 * ## 문안 규약 (2026-08-26 전수 감사에서 정리)
 *
 * 목적은 하나다 — **플레이어가 쉽게 읽고 이해해서 활용법을 스스로 상상하게 하는 것.**
 * 그래서 어떻게 플레이하라고 일러 주지 않는다.
 *
 * 요약(이 파일):
 * 1. ① 이 증강이 실제로 하는 동작 ② 놓치면 «고장»으로 읽을 조건, 둘을 넣는다.
 *    곁가지 부수 효과보다 큰 보상을 앞에 둔다.
 * 2. 조건이 깨지면 효과가 통째로 사라지는 증강은 그 «전부 잃는 조건»을 반드시 넣는다
 *    (묵계 — 평범한 퐁을 하나만 더 해도 멘젠이 사라진다).
 * 3. 배지가 말한 빈도를 본문에서 되풀이하지 않는다. 단 매치 예산과 국당 한도를 **함께**
 *    진 증강은 `briefBadgeMatchBudget.test.ts`가 본문에 「국당 1회」를 요구한다.
 * 4. ⚠ 국 단위 쿨다운을 「동풍전N·반장전M」 배지로 옮기지 마라 — `forMode`가 판 중에
 *    「게임 N회」로 접어 **없는 상한을 만든다**(본장·연장으로 국이 늘면 그보다 많이 쓴다).
 *
 * 상세(`AugmentDef.detail`):
 * 5. «무엇을 한다 → 언제 열린다 → 무엇은 안 된다» 순서의 평서문 1~2문단, 120~180자 기본.
 *    한 문단은 한 주제. (배타가 있는 증강은 출고 때 문단이 하나 자동으로 더 붙는다 —
 *    `conflictNotes.ts`. 그 줄은 소스에 손으로 적지 않는다.)
 * 6. 첫머리에 `(매 국 1회)` 같은 **괄호 머리말을 쓰지 않는다** — `expandParas`가 떼어 내
 *    화면에 안 뜬다. 두 번째 이후 문단이 `(`로 시작하면 테스트가 깨진다.
 * 7. 첫 문장은 «무엇을 하는 증강인가»를 다시 세운다. 예외 목록으로 시작하지 않는다.
 * 8. 구현 근거(「~이기 때문」)·개발 뒷사정·화면 사정은 쓰지 않는다.
 * 9. 흔치 않은 예외와 마작 상식(「리치를 걸면 손이 잠긴다」)은 뺀다. 다만 **이 증강 때문에
 *    «될 것 같은데 안 되는» 것**은 남긴다(묵계의 핑후, 개문선언의 멘젠쯔모).
 *    **상한·캡은 예외가 아니다 — 반드시 남긴다.**
 * 10. 굵게(`**`)는 한 증강에 한 곳, 모르면 손해가 확정되는 자리에만.
 *
 * 두 층 공통:
 * 11. 전략 코칭·가치 판단·독자 말걸기 금지 — 「핵심은 ~이다」 「~할수록 내 몫이 커진다」
 *     「고르면 된다」 「~하는 것이 상대의 수다」. 선택지를 설명해야 하면 **결과만** 적는다.
 * 12. 같은 사실을 방향만 바꿔 두 번 말하지 않는다. ①② 번호를 쓰지 않는다.
 * 13. 숫자는 옮겨 적기만 하고 새로 만들지 않는다 — `description_numbers.test.ts`가
 *     글의 모든 숫자를 그 증강 모듈 소스와 대조한다. 4자리 이상은 자릿점(`1,000점`).
 * 14. `description` 맨 앞 괄호의 숫자·표기는 손대지 않는다(테스트가 코드와 대조한다).
 */
