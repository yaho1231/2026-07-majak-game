/**
 * 화면 흔들림 세기.
 *
 * ── ⚠ 여기 숫자를 올리기 전에 읽을 것 ──
 *
 * 처음에는 옛 CSS 키프레임의 최대 변위를 **그대로** 옮겼다(2·5·9·14px, 진동 5~8회).
 * "체감을 바꾸지 않으려고" 그렇게 했는데, 실제로 계속 플레이해 보니 **볼 때마다
 * 어지러웠다**(2026-08-22 사용자 보고). 한 번 볼 때 적당한 세기와, 한 국에 여러 번
 * 겪을 때 견딜 수 있는 세기는 다르다 — 연출을 고를 때는 앞의 것만 보게 된다.
 *
 * 그래서 세 가지를 **함께** 줄였다. 어지러움은 진폭 하나가 아니라 진폭 × 진동 횟수 ×
 * 지속시간이 같이 만든다:
 *   실제 변위 14 → 6px · 진동 8 → 5회 · 0.62 → 0.34초 (가장 센 단계 기준)
 *
 * ⚠ **`amp` 는 실제 변위의 절반이다.** `fromTo(x: -amp → 0)` 에 CustomWiggle 을 걸면
 *   이징이 그 구간을 **넘어서** 진동하므로 최대 변위가 `amp × 1.95` 가 된다. 눈금이
 *   보이는 대로가 아니라서, 처음 줄일 때 이걸 모르고 잡았다가 실제로는 16% 밖에
 *   안 줄었다. 값을 바꾸면 **점검 페이지에서 실측**하고 여기 표를 갱신할 것:
 *
 *   | 단계 | amp | 실측 변위 |
 *   | 1 | 0.5 | 약 1.0px |
 *   | 2 | 1   | 약 1.9px |
 *   | 3 | 2   | 약 3.9px |
 *   | 4 | 3   | 약 5.9px |
 *
 * 지금 가장 센 4단(역만)이 예전 1단(2px)의 세 배쯤이고 예전 2단(5px)과 비슷하다.
 * 그래도 충분하다 — 흔들림은 "무언가 일어났다"를 알리는 신호지 사건 자체가 아니고,
 * 사건은 컷인 글자와 소리가 전한다.
 *
 * 세기 단계는 **얼마나 드문 사건인가**로만 정한다:
 *   1 = 깡처럼 국에 몇 번 · 2 = 리치·화료 · 3 = 큰 화료 · 4 = 역만(판에 한 번 있을까)
 */
