export interface GlossaryEntry {
  /** 안정적인 식별자 (툴팁 key) */
  key: string;
  /** 설명집에서 묶이는 분류 */
  group: GlossaryGroup;
  /** 툴팁 제목 — 기본 매칭 표기이기도 하다 */
  label: string;
  /** 초보자용 한 줄 풀이 */
  short: string;
  /**
   * 설명집에서만 쓰는 긴 풀이. 툴팁은 언제나 `short`다 — 손패 위에 뜨는 말풍선에
   * 세 줄을 넣으면 판이 가려진다. 처음 하는 사람이 한 줄로는 못 그리는 개념
   * (리치·후리텐·부수처럼)에만 붙인다. 전부에 붙일 필요가 없다.
   */
  long?: string;
  /** 본문에서 이 용어로 인식할 표기들(정규식 소스). 생략하면 label 하나. */
  match?: readonly string[];
  /**
   * **판 위에만** 뜨는 표기 — 증강 설명·요약에는 한 번도 안 나온다.
   *
   * 수록 기준은 "플레이어가 실제로 읽는 글"이지, "증강 설명에 나오는 말"이 아니다.
   * 대국 화면이 직접 찍는 말(형식 텐파이 등)도 처음 보면 모르기는 마찬가지인데,
   * 미사용 항목을 잡는 테스트가 증강 텍스트만 코퍼스로 보므로 여기서 갈라 준다.
   */
  hudOnly?: boolean;
}

