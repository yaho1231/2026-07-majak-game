/**
 * decide — 봇의 모든 행동이 만나는 한 자리.
 *
 * 예전 `BotAgent.decideNow`는 **고정된 우선순위 사슬**이었다.
 *
 *     화료 → 증강 → 깡 → 후로 → 리치 → 버림
 *
 * 각 단계는 "한다/안 한다"만 돌려줬고, 앞 단계가 하겠다고 하면 뒤 단계는 아예
 * 물어보지도 않았다. 그래서 봇은 **비교를 한 적이 없다.** 지금 이 펑이 리치보다
 * 이득인지, 이 깡이 안전패 하나보다 나은지 물을 자리가 구조적으로 없었다.
 * 새 판단(증강 계열, 새 콜)을 붙이려면 사슬 어딘가에 끼워 넣어야 했고, 그 위치가
 * 곧 판단이 되어 버렸다 — 판단하지 않은 판단이다.
 *
 * 지금은 모든 후보가 **점수(EV)로 입찰**하고, 이긴 것이 실행된다.
 *
 * ## 두 개의 층 — 우선순위가 아니라 게임의 사실
 *
 * 층이 남아 있지만 그건 취향이 아니라 규칙이다. **어떤 행동은 내 결정을 끝내지
 * 않는다.** 깡을 치면 영상패를 뽑고 다시 프롬프트가 오고, 증강을 발동해도 버림은
 * 그대로 남는다. 이런 행동은 다른 행동과 *경쟁하지 않는다* — 둘 다 할 수 있다.
 * 그러니 이득이 양수이기만 하면 먼저 하는 것이 옳다.
 *
 * | 층 | 행동 | 입찰값의 뜻 | 뽑는 법 |
 * |----|------|-------------|---------|
 * | 화료 | 론·쯔모 | — | 무조건 |
 * | 추가 행동 | 깡 · 액티브 증강 | **안 했을 때 대비 이득** | 양수 중 최대 |
 * | 턴 소비 | 버림 · 리치 · 후로 · 패스 | **그 행동을 한 뒤 판의 절대 EV** | 최대 |
 *
 * 턴 소비 층이 절대 EV인 이유: 패스와 후로, 버림과 리치는 서로를 배제하므로
 * "그 길로 갔을 때 이 판이 얼마짜리인가"를 직접 견주는 것이 맞다. 추가 행동 층이
 * 한계 이득인 이유: 기준선이 "안 한다"이기 때문이다.
 *
 * ## 왜 이게 확장에 강한가
 *
 * 새 판단을 붙이는 일이 **사슬에 끼워 넣기**에서 **입찰자 하나 추가**로 바뀐다.
 * 증강 100개가 더 들어와도 사슬은 자라지 않는다 — 전부 같은 축에서 입찰한다.
 * 그리고 모든 결정에 `reason`이 붙어, 봇이 왜 그렇게 뒀는지가 기록으로 남는다.
 */

import type { ActionOption } from "@majak/core/mahjong/flow/FlowController.js";

/** 한 행동의 입찰 */
export interface ActionBid {
  option: ActionOption;
  /**
   * 점수 단위의 값. 층에 따라 뜻이 다르다 —
   * 추가 행동은 **안 했을 때 대비 이득**, 턴 소비는 **그 뒤 판의 절대 EV**.
   */
  value: number;
  /** 왜 이 값이 나왔는가 — 리플레이 분석·회귀 추적·사람이 읽는 설명용 */
  reason: string;
}

/**
 * 추가 행동(깡·증강)이 실행되려면 넘어야 하는 문턱.
 *
 * 0으로 두면 반올림 오차 수준의 이득에도 깡을 치고 증강을 태운다 — 사람 눈에는
 * "쓸데없이 부산한" 봇이 된다. 손해가 아니라 **이득이 눈에 보일 때만** 움직인다.
 */
export const EXTRA_ACTION_FLOOR = 60;

/** 입찰 중 가장 값이 큰 것. 동점은 먼저 들어온 쪽(결정론) */
export function bestBid(bids: readonly (ActionBid | null)[]): ActionBid | null {
  let best: ActionBid | null = null;
  for (const b of bids) {
    if (b === null) continue;
    if (best === null || b.value > best.value) best = b;
  }
  return best;
}

/**
 * 증강 정책의 **발동 강도**(0~100)를 점수 축으로 옮긴다.
 *
 * 증강 정책들은 `BOT_WEIGHT`라는 별도 눈금으로 말한다(win 90 · defend 75 ·
 * advance 60 · normal 50 · setup 35 · info 20). 그 눈금은 증강끼리 비교하는 데는
 * 충분했지만 깡·리치·버림과는 비교할 수 없었다 — 축이 달랐기 때문이다.
 * 정책 115개를 전부 고쳐 쓰는 대신 **눈금 사이에 환율을 둔다.** 정책은 지금 쓰는
 * 말을 그대로 쓰고, 코어가 그 말을 점수로 옮긴다.
 *
 * 환율은 강도에 대해 지수적이다 — 강도가 선형이 아니라 등급 언어이기 때문이다.
 * 기준점: 평시(50) ≈ 손 값어치의 10%, 화료급(90)은 그 10배, 정보(20)는 1/5 남짓.
 * 손이 비쌀수록 같은 강도의 증강이 실제로 더 값나가므로 손 값어치에 매단다.
 */
export function augmentPoints(weight: number, handPoints: number): number {
  const base = Math.max(AUGMENT_BASE_FLOOR, Math.min(1600, handPoints * 0.12));
  return base * Math.exp(0.0576 * (weight - 50));
}

/**
 * **환율의 바닥** — 싼 손에서도 환율이 이 아래로는 안 내려간다.
 *
 * ## 400이던 시절, 정보형 증강은 싼 손에서 켤 수가 없었다
 *
 * 두 문턱이 서로를 모르고 서 있었다. `botPlan`은 적기(readiness) 0.35부터 정보형
 * 증강의 입찰을 **만들고**, 여기 환율은 그 입찰을 점수로 옮기고, `EXTRA_ACTION_FLOOR`
 * (60)가 그 점수를 **버렸다.** 손이 3,333점 이하면 `base`가 400으로 눌리는데,
 * 그 자리에서 정보 강도(`BOT_WEIGHT.info` 20)의 입찰은 이렇게 된다.
 *
 * ```
 * 적기 0.35 → 43.1   적기 0.50 → 46.6   적기 0.75 → 53.1   적기 1.00 → 60.4
 *              ↑ 전부 문턱 60 아래. 적기가 정확히 1.0일 때만, 그것도 0.4점 차로 넘는다.
 * ```
 *
 * 정보형 적기는 `max(위협, 손의 여묾, (turn−3)/8)`이라 **11순이 되어야** 1.0에
 * 닿는다(`botPlan.readiness`). 즉 예지·이면투시·삼자택일·우라 엿보기는 싼 손에서
 * **10순까지는 아무리 때가 맞아도 켤 수 없었다.** 매 순 입찰을 계산해서 버리고 있었다.
 *
 * ## 왜 여기를 고치는가
 *
 * 셋 중 하나를 움직여야 한다. `EXTRA_ACTION_FLOOR`를 내리면 깡 판단까지 헐거워지고,
 * `MIN_READINESS.inform`을 0.94로 올리면 "적기 문턱"이 사실은 문턱이 아니라 장식임을
 * 인정하는 꼴이다. 틀린 것은 **환율의 바닥**이다 — 400은 "정책이 낸 입찰 중 가장 약한
 * 것도 문턱을 넘는가"를 한 번도 확인하지 않고 고른 값이다.
 *
 * 지금 값은 그 확인에서 나왔다: 가장 불리한 점(강도 20 · 적기 0.35 · 가장 참을성 있는
 * 원형의 ×0.85)에서 `60 / (e^(0.0576×(14.15−50)) × 0.85) ≈ 557`이 하한이고, 여유를
 * 두어 700으로 잡는다 → 그 점에서 75.5. 이제 **정책이 만든 입찰은 전부 견줄 자격을
 * 갖는다.** 이 관계는 `BotDecide.test.ts`가 손 값어치 전 구간에서 잡는다.
 *
 * 실측(2026-08-08, 84배패 2:2 · 증강 전체): 순위 +0.0000 ± 0.0000 · 점수 +21 ± 21.
 * **강함으로는 잴 수 없다** — 정보형은 117종 중 4종이라 표본이 안 쌓인다(점수 차가
 * 0이 아닌 것이 스위치가 실제로 읽혔다는 증거다). 근거는 측정이 아니라 위 산수다.
 */
const AUGMENT_BASE_FLOOR = 700;
