/**
 * flags — 봇의 **실험 스위치**.
 *
 * ## 왜 필요한가
 *
 * 측정 하네스(`bot/arena.ts`)는 봇 넷을 같은 정책으로 앉힌다. 그러면 평균 순위가
 * **구조상 2.5로 수렴한다** — 넷이 같은 사람이니 당연하다. 그래서 지금까지 잰 것은
 * 유국률·총 화료율 같은 '판의 효율'이었고, **"이 변경이 봇을 더 강하게 만들었는가"는
 * 한 번도 재지 못했다.**
 *
 * 강함은 상대적인 값이라 **같은 탁에 둘을 앉혀야** 잴 수 있다. 그러려면 한 프로세스
 * 안에서 두 정책이 동시에 살아 있어야 하고, 그게 이 파일이 있는 이유다.
 *
 * ## 쓰는 법
 *
 * 새 판단을 넣을 때 곧바로 갈아치우지 않고 스위치 뒤에 둔다.
 *
 *     if (read.flags.has("yaku2")) { …새 방식… } else { …기존 방식… }
 *
 * 그리고 2:2로 붙여 평균 순위를 본다.
 *
 *     npm run arena -- --games 200 --ab yaku2
 *
 * 이겼으면 스위치를 지우고 새 방식만 남긴다. **스위치는 영구 설정이 아니라 임시
 * 비계다** — 남겨 두면 코드가 두 갈래로 굳는다.
 *
 * ## 예외: 끄는 스위치
 *
 * 반대 방향으로 쓰는 것 몇 개는 남겨 둔다 — 이미 켜져 있는 하위 시스템을 **끄는**
 * 스위치다. 그러면 "이 부분이 지금 얼마나 기여하고 있는가"를 언제든 다시 잴 수 있다.
 * 켜는 스위치는 채택하면 지우지만, 끄는 스위치는 자(尺)의 일부다.
 *
 *   - `noYakuRead` — 손을 직접 읽어 역을 잡는 것을 끈다 (`bot/yaku.ts`)
 *   - `noSuji` — 스지 읽기를 끈다. 량면 감액이 사라지고 벽·장수 셈만 남는다 (`bot/suji.ts`)
 *
 * ## 예외 2: 재 보고 반려했지만 남겨 둔 것
 *
 * `menzenfu` — 멘젠 부수 분리(`bot/read.ts`). 마작으로는 이쪽이 옳은데 후로율을
 * 4.2%p 깎아 이번 목표와 어긋나 반려했다. 후로 값매김을 손본 뒤 **다시 재려면**
 * 스위치가 있어야 하므로 판정 기록과 함께 남긴다.
 *
 * ## 채택되어 사라진 것 (2026-08-08)
 *
 * `passrisk` · `damaten` · `place2` — 셋 다 2:2 대전에서 강함이 그대로였고(순위 차가
 * 전부 표준오차 안), 모형이 옳아지므로 기본 동작이 되었다. 각 자리의 주석에 실측이
 * 남아 있다.
 */

/** 켜져 있는 실험 스위치 (비어 있으면 기본 동작) */
export type BotFlags = ReadonlySet<string>;

/** 아무것도 켜지 않은 기본값 — 실대국 봇이 쓰는 값이다 */
export const NO_FLAGS: BotFlags = new Set<string>();

/** 쉼표로 이어 붙인 문자열을 스위치 집합으로 (CLI·테스트용) */
export function parseFlags(spec: string | undefined): BotFlags {
  if (spec === undefined || spec.trim() === "") return NO_FLAGS;
  return new Set(
    spec
      .split(",")
      .map((s) => s.trim())
      .filter((s) => s.length > 0),
  );
}
