/**
 * skill — **난이도가 판에서 실제로 보이게 만드는 자리.**
 *
 * ## 왜 이 파일이 생겼나 (QA 4라운드 P1)
 *
 * `profile.skill`은 오래도록 `bot/discard.ts`의 `wobble` 밴드 **한 곳**에서만 쓰였다.
 * 즉 난이도를 낮춰도 봇은 "쓸모가 엇비슷한 후보들" 사이에서 조금 더 흔들릴 뿐,
 * 리치·후로·깡·수비·순위 판단은 100% 동일했다. 측정이 그대로 답했다 —
 * easy 둘 : hard 둘 듀플리케이트 120판에서 평균 순위 차 **0.075 ± 0.057(1.3σ)**.
 * 대기실은 「쉬움 — 실수를 자주 한다」고 약속하는데 판에서는 아무 일도 없었다.
 *
 * ## 무엇을 실수로 삼는가
 *
 * 초보가 실제로 하는 실수는 "규칙을 모른다"가 아니라 **위험과 순위를 못 본다**다.
 * 그래서 난이도를 판단 **규칙**에 붙이지 않는다(그러면 easy 봇이 마작이 아닌 것을
 * 두게 된다). 대신 이 저장소가 이미 갖고 있는 두 축의 **무게**를 깎는다:
 *
 *   1. `expectedLoss`(방총 위험) — 낮은 실력은 위험패를 싸게 본다 → 밀어야 할 자리가
 *      아닌데 밀고, 접어야 할 자리에서 안 접는다.
 *   2. `match.riskAppetite`(순위 압박) — 낮은 실력은 점수판을 잘 안 본다 → 올라스
 *      선두인데 리치를 걸고, 굳은 순위에서 무리한다.
 *
 * 그리고 그 결과로 **리치·후로·깡이 헐거워진다** — 판에서 눈에 보이는 것은 이쪽이다.
 * 강한 쪽(`skill = 1`)에서는 모든 계수가 정확히 1이라 **hard는 종전 봇 그대로**다.
 * (`DIFFICULTY_SKILL`이 hard를 1.0으로 두는 이유와 같다 — 위로 열지 않는다.)
 */

import type { BotProfile } from "./profile.js";

/** 0~1로 묶은 실력 눈금. 프로필이 이상한 값을 들고 와도 계수는 성립한다. */
export function skillOf(profile: BotProfile): number {
  const s = profile.skill;
  return Number.isFinite(s) ? Math.max(0, Math.min(1, s)) : 1;
}

/**
 * **위험을 얼마나 제값으로 세는가** (0 = 위험이 안 보인다, 1 = 제값).
 *
 * easy(0.35) → 0.58. 방총 기대 실점을 6할만 세니, 같은 손에서도 무스지를 통과시키고
 * 남의 리치에 계속 민다. 큰 손을 못 알아보는 것이 아니라 **싸게 본다**는 뜻이라,
 * 봇은 여전히 마작을 두면서 진다.
 */
export const riskSight = (skill: number): number => DANGER_FLOOR + (1 - DANGER_FLOOR) * skill;
const DANGER_FLOOR = 0.35;

/**
 * **점수판을 얼마나 보는가** (0 = 안 본다, 1 = 다 본다).
 *
 * 순위 압박은 곱이 아니라 그냥 눈금이 줄어드는 축이라 선형으로 깎는다.
 * easy는 올라스 선두에서도 평시처럼 두고, 굳은 4위에서 밀어야 할 때 안 민다.
 */
export const placementSight = (skill: number): number => PLACEMENT_FLOOR + (1 - PLACEMENT_FLOOR) * skill;
const PLACEMENT_FLOOR = 0.15;

/**
 * **헐거움** — 리치·후로·깡 쪽 이득에 얹는 웃돈 (1 = 종전).
 *
 * easy(0.35) → 1.26. 초보는 "일단 걸고 본다 / 일단 부르고 본다"를 한다. 위험을
 * 싸게 보는 것(위 `riskSight`)과 합쳐지면 판에서 바로 보인다 — easy 봇 탁은 리치와
 * 후로가 잦고 방총이 많다. 폭을 크게 잡지 않는 이유는, 크게 잡으면 실수가 아니라
 * **다른 게임을 두는 봇**이 되어 사람이 배우는 데 방해가 되기 때문이다.
 */
export const looseness = (skill: number): number => 1 + (1 - skill) * LOOSE_SPAN;
const LOOSE_SPAN = 0.4;

/**
 * **실수의 크기** — 실력이 낮을 때 「엇비슷하다」고 보는 폭에 더하는 **점수 단위 바닥**.
 *
 * ## 왜 0이 됐나 (2026-09-07)
 *
 * 이 바닥은 «최선보다 이만큼 손해까지는 **아무거나** 고른다»였다. 실력을 깎기는 했지만
 * 깎는 방식이 사람의 실수와 달랐다 — 초보도 아무 패나 던지지는 않는다. 그리고 그
 * «아무거나»가 아래 `lapseChance`의 **차선 고르기보다 더 큰 실수**여서, 느슨한 순번을
 * 늘릴수록 봇이 오히려 강해지는 역설이 있었다(실측: lapse를 넣자 순위차가
 * -0.650 → -0.500으로 **줄었다**).
 *
 * 그래서 난이도의 **본체**를 「가끔 그럴듯한 차선을 고른다」(`lapseChance`)로 옮기고,
 * 이 바닥은 600 → 250으로 줄여 남긴다. 완전히 없애지 않는 이유는 사람도 «아무래도
 * 좋은 자리»에서는 실제로 대충 고르기 때문이다 — 다만 그게 실력의 전부여서는 안 된다.
 */
export const blunderFloor = (skill: number): number => (1 - skill) * BLUNDER_POINTS;
const BLUNDER_POINTS = 250;

/**
 * **고르기의 온도** — 「최선 대신 차선을 고를 확률」을 정하는 점수 눈금.
 *
 * ## 왜 균등 추첨이 아니라 온도인가 (2026-09-07)
 *
 * 밴드 안에서 **균등하게** 뽑으면 두 가지가 어긋난다. (1) 밴드에 들어오기만 하면
 * 최선과 최악이 같은 확률이라, 밴드를 넓히는 순간 봇이 «가끔 조금 손해»가 아니라
 * «자주 많이 손해»를 본다. (2) 그래서 밴드를 넓힐 수 없고, 밴드가 좁으니 후보는
 * 언제나 **같은 샹텐을 유지하는 패들**뿐이었다 — easy 봇도 텐파이 속도는 hard와
 * 똑같았다(실측: 듀플리케이트 120판에서 화료율 0.134 : 0.221, 방총률 0.135 : 0.080 —
 * 차이가 전부 «쏘인다»에서만 나왔다).
 *
 * 온도를 쓰면 확률이 EV 차이에 따라 **부드럽게** 떨어진다(`exp(-Δ/T)`). 최선이
 * 여전히 가장 자주 뽑히고, 조금 나쁜 수는 가끔, 많이 나쁜 수는 드물게 —
 * 사람이 «이쪽이 나은 건 알지만 넓은 대기가 탐나서» 고르는 모습이 이 모양이다.
 * easy(0.35) → 715점: 715점 손해인 수를 최선 대비 37% 비율로 고른다.
 * hard(1)에서는 0이라 **온도 경로 자체가 꺼진다**(종전 균등 밴드 그대로).
 */
export const blunderTemp = (skill: number): number => (1 - skill) * TEMP_POINTS;
const TEMP_POINTS = 1100;

/**
 * **후보로 쳐 주는 손해의 한계** — 온도의 몇 배까지 볼 것인가.
 *
 * 3배면 최선 대비 `exp(-3) ≈ 5%` 비율까지가 후보다. 이 한계가 있어야 「초보라서
 * 조금 손해 보는 수」와 「마작이 아닌 수」가 갈린다 — 리치에 정면으로 쏘는 무스지처럼
 * EV가 통째로 무너지는 선택은 온도가 아무리 높아도 들어오지 않는다.
 */
export const BLUNDER_CUT = 3;

/**
 * **느슨한 순번에 놓고 보는 후보 수.**
 *
 * 폭(`BLUNDER_CUT`)만으로 자르면 EV가 다 고만고만한 국면에서 열 장이 통째로 후보가
 * 되고, 그러면 «차선을 고른다»가 아니라 «아무거나 고른다»가 된다 — 실측으로 easy의
 * 화료율이 0.009까지 떨어졌다(hard 0.274). 사람이 망설이는 것은 **한두 장 사이**다.
 * 그래서 EV 상위 셋만 놓고 그중에서 온도로 고른다 — 사용자가 말한 「50%·30%·20%」의
 * 모양이 정확히 이것이다.
 */
export const LAPSE_TOP = 3;

/**
 * **한 순에 «느슨하게 고를» 확률.**
 *
 * ## 왜 매 순번이 아닌가 (2026-09-07 실측)
 *
 * 처음에는 실력이 낮으면 **모든 순번**을 온도로 골랐다. 그러면 순번마다의 작은
 * 어긋남이 18순 내내 곱해져 손이 통째로 무너진다 — easy의 화료율이 0.005까지
 * 떨어졌다(hard 0.286). 그건 «가끔 비효율적인 타패»가 아니라 마작을 두지 않는 봇이다.
 *
 * 사람의 초보다움은 매 순간 조금씩 어긋나는 것이 아니라 **가끔 한 번 다르게 두는**
 * 것이다("이게 나은 건 아는데 이쪽 대기가 넓어 보여서"). 그래서 느슨한 고르기를
 * 순번마다가 아니라 **확률로** 켠다. easy(0.35)는 0.39, normal(0.7)은 0.18 — 한 국(약 12~16순)에
 * easy가 대여섯 번, normal이 두어 번이다. 나머지 순번은 성격만 흔들리는 **종전 그대로**이므로, 실력이 낮아도
 * 손은 정상적으로 자란다.
 */
export const lapseChance = (skill: number): number => (1 - skill) * LAPSE_RATE;
const LAPSE_RATE = 0.6;

/**
 * **초보는 몇 샹텐 뒤처지는 형태까지 «후보»로 보는가.**
 *
 * 여기가 손 효율에 난이도가 닿는 유일한 자리다. `discard.shapesOf`는 원래 **최선
 * 샹텐을 유지하는 후보만** 우케이레·대기를 정밀하게 쟀다 — 그보다 나쁜 형태는
 * 우케이레 0으로 남아 화료 확률이 바닥이라, 흔들림 폭을 아무리 넓혀도 **후보에
 * 들어올 수가 없었다.** 그래서 난이도가 텐파이 속도를 한 번도 못 건드렸다.
 *
 * 실력이 1보다 낮으면 한 샹텐 뒤처지는 형태까지 제대로 잰다. 그러면 「지금 텐파이를
 * 포기하는 대신 나중에 대기가 넓어지는 형태」가 **제 EV를 갖고** 후보에 올라오고,
 * 위의 온도가 그걸 가끔 고른다. 재는 값 자체는 정확하므로(대충 세지 않는다)
 * 형편없는 형태는 여전히 EV에서 지고 걸러진다.
 *
 * hard(1)는 0이라 계산량도 종전 그대로다.
 */
export const shapeSlack = (skill: number): number => (skill < 1 ? 1 : 0);
