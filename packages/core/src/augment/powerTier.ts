/** 총점 → 티어 하한 (SS+는 점수가 아니라 "발동=역만·배만 확정"이라는 성질로 지정한다) */
export const TIER_CUTS: readonly { tier: PowerTier; min: number }[] = [
  { tier: "S+", min: 41 },
  { tier: "S", min: 36 },
  { tier: "A", min: 29 },
  { tier: "B", min: 23 },
  { tier: "C", min: 17 },
  { tier: "D", min: 0 },
];

export interface PowerTierEntry {
  /** 확정 티어 (rare 보정·SS+ 지정 반영 후) */
  tier: PowerTier;
  /** 타점 1~5 */
  p: number;
  /** 속도 1~5 */
  s: number;
  /** 무대응 1~5 */
  u: number;
  /** 빈도 1~5 */
  f: number;
  /** 한 줄 사유 */
  note: string;
  /** 조건이 극단적으로 드물어 산식 총점보다 낮춘 항목 (낮추는 방향 전용) */
  rare?: boolean;
  /**
   * 산식 총점이 가리키는 티어와 **다른 티어를 손으로 지정한 사유**.
   *
   * `rare`로 설명되지 않는 모든 이탈(올린 것 · 드물어서가 아닌 이유로 내린 것)에 붙인다.
   * 왜 p·s·u·f 네 축이 이 증강을 못 담는지를 적는 자리다 — "강해 보여서"는 사유가 아니다.
   * 정직하게 못 적는 값은 `⚠ 재평가 필요 —` 로 시작해 빚으로 남긴다(파일 머리말 참고).
   */
  tierOverride?: string;
}

/** 총점 = p*3 + s*3 + u*2 + f*2 */
export function powerScore(e: PowerTierEntry): number {
  return e.p * 3 + e.s * 3 + e.u * 2 + e.f * 2;
}

/**
 * 산식 총점이 가리키는 티어 (`TIER_CUTS`).
 *
 * SS+는 점수가 아니라 성질로 지정하므로 이 함수는 SS+를 돌려주지 않는다 —
 * SS+ 행은 정의상 항상 산식과 어긋나며, `tierOverride`로 그 성질을 적어 둔다.
 */
export function formulaTier(score: number): PowerTier {
  for (const cut of TIER_CUTS) {
    if (score >= cut.min) return cut.tier;
  }
  return "D";
}

/** 이 행이 산식과 어긋나는가 (어긋나면 `rare` 또는 `tierOverride`가 있어야 한다) */
export function deviatesFromFormula(e: PowerTierEntry): boolean {
  return e.tier !== formulaTier(powerScore(e));
}

/**
 * 봇 발동 강도 기본값 (0~100) — 정책이 `{option, weight}`로 강도를 명시하지 않았을 때 쓴다.
 *
 * 액티브를 둘 이상 보유한 봇은 한 프롬프트에 하나만 제출할 수 있다. 예전에는 보유 배열의
 * 첫 non-null이 무조건 이겨 **픽 순서**가 판단을 눌렀다(docs/25 시스템 횡단 #10). 강도를
 * 안 밝힌 정책끼리는 "더 센 증강을 먼저 태운다"가 픽 순서보다 낫다 — 파워 점수(최대 50)를
 * 2배해 0~100 축에 올린다. 티어표에 없는 id는 평시값(BOT_WEIGHT.normal = 50).
 *
 * 예외로 `info` 계열은 파워와 무관하게 항상 뒤로 민다(BOT_WEIGHT.info). 정보는 한 순
 * 늦게 봐도 거의 손해가 없는 반면, 같은 프롬프트의 다른 액티브는 그 순이 지나면 기회를
 * 잃는 것이 보통이다.
 */
export function defaultBotWeight(
  augmentId: string,
  category?: AugmentCategory,
): number {
  if (category === "info") return BOT_WEIGHT.info;
  const entry = AUGMENT_POWER_TIERS[augmentId];
  return entry === undefined ? BOT_WEIGHT.normal : Math.min(100, powerScore(entry) * 2);
}

