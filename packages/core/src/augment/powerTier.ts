/**
 * 실측 종합점수 → 티어 하한. 산식 컷과 같은 `quantileCuts`를 쓴다 — 티어별 수량이
 * 표의 크기와 무관하게 고르게 유지되는 성질을 그대로 물려받는다.
 */
export const MEASURED_CUTS: readonly { tier: PowerTier; min: number }[] = quantileCuts(
  Object.values(AUGMENT_MEASURED).map((e) => e.m),
);

/** 실측 종합점수가 가리키는 티어. SS+는 여기서 나오지 않는다(성질로 지정한다). */
export function measuredTier(m: number): PowerTier {
  for (const cut of MEASURED_CUTS) {
    if (m >= cut.min) return cut.tier;
  }
  return "D";
}

/**
 * 이 행의 티어가 어디서 나왔는가 — 실측이 있으면 실측, 없으면 산식.
 * `shift`는 그 위에 얹는다(실측 대상 행에는 지금 하나도 없다).
 */
export function baseTier(id: string, spec: PowerTierSpec): PowerTier {
  const measured = AUGMENT_MEASURED[id];
  return measured === undefined ? formulaTier(powerScore(spec)) : measuredTier(measured.m);
}

/**
 * 총점 → 티어 하한. **표의 점수 분포에서 분위수로 계산한다** (`quantileCuts`).
 *
 * `fixed`(SS+)는 모집단에서 뺀다 — 점수와 무관하게 지정된 행이라 분위수 경계를
 * 밀 이유가 없다. 표가 바뀌면 이 값도 바뀐다: 고정 상수가 아니다.
 */
export const TIER_CUTS: readonly { tier: PowerTier; min: number }[] = quantileCuts(
  Object.values(AUGMENT_POWER_SPECS)
    .filter((e) => e.fixed === undefined)
    .map(powerScore),
);

/**
 * 증강 id → 확정 파워 티어.
 *
 * **실측 종합점수**(`AUGMENT_MEASURED`)를 분위수 컷에 태우고 `shift`만큼 옮긴 결과다.
 * 실측이 없는 행(동풍전 전용)만 종전대로 산식 총점을 쓴다 — `baseTier`.
 * `fixed`가 있으면 점수를 무시하고 그 값을 쓴다(SS+).
 */
export const AUGMENT_POWER_TIERS: Readonly<Record<string, PowerTierEntry>> =
  Object.fromEntries(
    Object.entries(AUGMENT_POWER_SPECS).map(([id, spec]) => [
      id,
      {
        ...spec,
        tier: spec.fixed ?? shiftTier(baseTier(id, spec), spec.shift ?? 0),
      },
    ]),
  );
