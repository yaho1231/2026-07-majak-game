import { configDefaults, defineConfig } from "vitest/config";

/**
 * 설정이 없으면 vitest 기본 exclude에 `.claude/`가 없어서 **워크트리 안의
 * 테스트까지 전부 긁어 온다**. 워크트리 10개가 붙어 있던 시점에 실제로
 * 테스트 파일 99개 → 981개, 실행 시간 165초 → 879초가 됐고, 사본들이 같은
 * 임시 디렉터리 이름을 동시에 쓰다 `ENOTEMPTY`로 무관한 파일이 줄줄이
 * 실패했다. 무엇보다 "master의 테스트 결과"를 신뢰할 수 없게 된다.
 */
export default defineConfig({
  test: {
    exclude: [...configDefaults.exclude, "**/.claude/**"],
    /**
     * CI 러너는 코어가 적어 `waitFor` 계열 타이밍 테스트가 부하로 굶어 터진다
     * (`RoomManager.test.ts`의 국 사이 대기 테스트 — 단독 실행은 항상 통과).
     * 게이트가 흔들리면 게이트를 안 보게 되므로 CI에서만 재시도를 켠다.
     * 로컬은 0 — 여기서 깜빡이면 그건 봐야 하는 신호다.
     */
    retry: process.env["CI"] === undefined ? 0 : 2,
    /**
     * 테스트 한 건의 제한 시간 (기본 5초 → 5분).
     *
     * **왜 이렇게 큰가**: 이 저장소의 테스트 상당수는 **실제 마작 한 국·한 판을
     * 끝까지 굴린다**(증강 크래시 스위프는 증강 하나당 8시드 × 한 국, `combo_sweep`은
     * 4인 × 2증강 반장전). 실측으로 한 건이 50~190초다 — 느린 것이 아니라 그게
     * 그 검사의 원가다(docs/23 "한 판의 실제 비용").
     *
     * **왜 지금 필요해졌나**: vitest 4 이전에는 이 제한이 **동기 테스트에 사실상
     * 적용되지 않았다** — 동기 본문은 중간에 끊을 수가 없어 끝까지 돌고 통과했다.
     * vitest 4가 끝난 뒤 경과 시간으로도 판정하면서 130건이 한꺼번에
     * `Test timed out in 5000ms`로 떨어졌다. 코드가 느려진 것이 아니라 **한 번도
     * 걸린 적 없던 제한이 이제 걸리는 것**이다.
     *
     * 진짜 멈춘 테스트를 놓치지 않느냐: 시간에 뜻이 있는 검사들은 이미 **자기
     * 예산을 명시**하고 있다(`RoomManager.test.ts`의 `HANCHAN_MS = 90초`,
     * `Guest.test.ts`의 `TONPUU_MS`). 그쪽이 실제 그물이고, 이 값은 "여기서 걸리면
     * 그건 무한 루프다" 선이다.
     */
    testTimeout: 300_000,
    hookTimeout: 60_000,
  },
});
